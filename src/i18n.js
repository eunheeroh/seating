// 메시지는 { key, args, extra } 로 보관 → 언어를 바꾸면 자동으로 다시 번역됨
export function formatMsg(t, msg) {
  if (!msg) return '';
  const val = t[msg.key];
  const text = typeof val === 'function' ? val(...(msg.args || [])) : (val ?? '');
  return text + formatMsg(t, msg.extra);
}
